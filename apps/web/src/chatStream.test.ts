import { test, expect } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseSse, applyEvent, initialStream, toViewMessages, sessionLabel, modelChoices, modelGroups, REASONING_CHOICES, reasoningOptions } from "./chatStream";

test("parseSse keeps a partial event until its blank line arrives", () => {
  const a = parseSse("", 'event: assistant.delta\ndata: {"delta":"po');
  expect(a.events).toEqual([]);
  const b = parseSse(a.rest, 'ng"}\n\nevent: run.completed\ndata: {"completed":true}\n\n');
  expect(b.events).toEqual([
    { event: "assistant.delta", data: { delta: "pong" } },
    { event: "run.completed", data: { completed: true } },
  ]);
});

test("applyEvent appends deltas in order", () => {
  let s = initialStream;
  s = applyEvent(s, { event: "assistant.delta", data: { delta: "Hel" } });
  s = applyEvent(s, { event: "assistant.delta", data: { delta: "lo" } });
  expect(s).toEqual({ text: "Hello", thinking: "", status: "streaming", error: "" });
});

test("run.completed marks the reply done and keeps the final assistant text", () => {
  let s = applyEvent(initialStream, { event: "assistant.delta", data: { delta: "pon" } });
  s = applyEvent(s, { event: "run.completed", data: { messages: [{ role: "assistant", content: "pong" }] } });
  expect(s.status).toBe("done");
  expect(s.text).toBe("pong");
});

test("run.failed carries the error text and stops streaming", () => {
  const s = applyEvent(initialStream, { event: "run.failed", data: { error: "model timeout" } });
  expect(s.status).toBe("error");
  expect(s.error).toBe("model timeout");
});

test("run.cancelled is a distinct terminal state", () => {
  expect(applyEvent(initialStream, { event: "run.cancelled", data: {} }).status).toBe("cancelled");
});

test("thinking events go to the thinking text, not the reply", () => {
  const s = applyEvent(initialStream, { event: "tool.progress", data: { tool_name: "_thinking", delta: "Checking the sessions" } });
  expect(s.text).toBe("");
  expect(s.thinking).toBe("Checking the sessions");
});

test("thinking deltas accumulate in order", () => {
  let s = applyEvent(initialStream, { event: "tool.progress", data: { tool_name: "_thinking", delta: "a" } });
  s = applyEvent(s, { event: "tool.progress", data: { tool_name: "_thinking", delta: "b" } });
  expect(s.thinking).toBe("ab");
});

test("a real tool progress event is not treated as thinking", () => {
  const s = applyEvent(initialStream, { event: "tool.progress", data: { tool_name: "terminal", delta: "ls" } });
  expect(s.thinking).toBe("");
});

test("gateway notices are hidden from the message list", () => {
  const out = toViewMessages([
    { role: "user", content: "[IMPORTANT: Background process proc_1 completed normally (exit code 0)." },
    { role: "user", content: "[INTERNAL NOTIFICATION — generated by the Hermes gateway]" },
    { role: "user", content: "[tun] hello" },
  ]);
  expect(out).toEqual([{ role: "user", content: "hello" }]);
});

test("the [tun] sender prefix and the triggering-id line are removed from messages", () => {
  const out = toViewMessages([
    { role: "user", content: "[Triggering message id: `1557612063562530836` — use as `message_id`]\n[tun] i checked previous session" },
  ]);
  expect(out).toEqual([{ role: "user", content: "i checked previous session" }]);
});

test("a truncated triggering-id title is cleaned too", () => {
  expect(sessionLabel({ title: "[Triggering message id: `1557550922362523753`…", preview: null })).toBe("New chat");
  expect(sessionLabel({ title: "[Triggering message id: `1557550922362523753`… [tun] check proxmox", preview: null })).toBe("check proxmox");
});

test("session titles drop the sender prefix and the triggering-id line", () => {
  expect(sessionLabel({ title: "[tun] control center unable to read proxmox", preview: null })).toBe("control center unable to read proxmox");
  expect(sessionLabel({ title: "[Triggering message id: `1` — x] [tun] go", preview: null })).toBe("go");
});

test("model choices flatten Hermes providers into provider-scoped values", () => {
  const choices = modelChoices({
    providers: [
      { slug: "nous", name: "Nous Portal", models: ["anthropic/claude-haiku-5.5", "openai/gpt-5.5"] },
      { slug: "anthropic", name: "Anthropic", models: ["claude-haiku-5-5"] },
    ],
  });
  expect(choices).toEqual([
    { value: "nous|anthropic/claude-haiku-5.5", label: "Nous Portal · anthropic/claude-haiku-5.5", provider: "nous", model: "anthropic/claude-haiku-5.5" },
    { value: "nous|openai/gpt-5.5", label: "Nous Portal · openai/gpt-5.5", provider: "nous", model: "openai/gpt-5.5" },
    { value: "anthropic|claude-haiku-5-5", label: "Anthropic · claude-haiku-5-5", provider: "anthropic", model: "claude-haiku-5-5" },
  ]);
});

test("model choices tolerate a missing or empty payload", () => {
  expect(modelChoices({})).toEqual([]);
  expect(modelChoices({ providers: [{ slug: "x", name: "X", models: [] }] })).toEqual([]);
});

test("reasoning choices offer off plus the Hermes effort levels", () => {
  expect(REASONING_CHOICES.map(c => c.value)).toEqual(["none", "low", "medium", "high"]);
});

test("a reasoning choice becomes Hermes model_options; off disables reasoning", () => {
  expect(reasoningOptions("high")).toEqual({ reasoning: { enabled: true, effort: "high" } });
  expect(reasoningOptions("none")).toEqual({ reasoning: { enabled: false } });
  expect(reasoningOptions("")).toBeUndefined();
});

test("a thinking block is collapsed by default", () => {
  const src = readFileSync(join(import.meta.dir, "pages", "Chat.tsx"), "utf8");
  expect(src).toMatch(/<details className="thinking"(?![^>]*\bopen\b)/);
});

test("tool events do not change the reply text", () => {
  const s = applyEvent(initialStream, { event: "tool.started", data: { tool: "terminal" } });
  expect(s).toEqual(initialStream);
});

test("toViewMessages keeps only user and assistant turns with text", () => {
  const raw = [
    { role: "user", content: "hi" },
    { role: "tool", content: "{}" },
    { role: "assistant", content: "hello" },
    { role: "assistant", content: null },
  ];
  expect(toViewMessages(raw)).toEqual([
    { role: "user", content: "hi" },
    { role: "assistant", content: "hello" },
  ]);
});

test("sessionLabel prefers the title, then the preview, then a placeholder", () => {
  expect(sessionLabel({ title: "Plan", preview: "x" })).toBe("Plan");
  const long = "Integrate Hermes chat into the control center with session switching and new chats";
  expect(sessionLabel({ title: null, preview: long })).toBe(long.slice(0, 60));
  expect(sessionLabel({ title: null, preview: "short" })).toBe("short");
  expect(sessionLabel({ title: null, preview: null })).toBe("New chat");
});

test("model groups split providers, skip empty ones, sort by name and model, and use bare model labels", () => {
  const groups = modelGroups({
    providers: [
      { slug: "nous", name: "Nous Portal", models: ["openai/gpt-5.5", "anthropic/claude-haiku-5.5"] },
      { slug: "anthropic", name: "Anthropic", models: ["claude-sonnet-5-5", "claude-haiku-5-5"] },
      { slug: "empty", name: "Empty", models: [] },
    ],
  });
  expect(groups).toEqual([
    {
      slug: "anthropic",
      name: "Anthropic",
      models: [
        { value: "anthropic|claude-haiku-5-5", label: "claude-haiku-5-5", model: "claude-haiku-5-5" },
        { value: "anthropic|claude-sonnet-5-5", label: "claude-sonnet-5-5", model: "claude-sonnet-5-5" },
      ],
    },
    {
      slug: "nous",
      name: "Nous Portal",
      models: [
        { value: "nous|anthropic/claude-haiku-5.5", label: "anthropic/claude-haiku-5.5", model: "anthropic/claude-haiku-5.5" },
        { value: "nous|openai/gpt-5.5", label: "openai/gpt-5.5", model: "openai/gpt-5.5" },
      ],
    },
  ]);
});

test("model groups drop repeated model ids within a provider", () => {
  const groups = modelGroups({
    providers: [{ slug: "nous", name: "Nous Portal", models: ["openai/gpt-5.5", "openai/gpt-5.5"] }],
  });
  expect(groups).toHaveLength(1);
  expect(groups[0].models.map(m => m.model)).toEqual(["openai/gpt-5.5"]);
});

test("model groups tolerate a missing or empty payload", () => {
  expect(modelGroups({})).toEqual([]);
  expect(modelGroups({ providers: [] })).toEqual([]);
});
